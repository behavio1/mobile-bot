import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const hostRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = join(hostRoot, "predefined-skills");
const output = join(hostRoot, "src", "generatedSkills.ts");

function filesBelow(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    return entry.isDirectory() ? filesBelow(path) : [path];
  });
}

const skills = {};
for (const entry of readdirSync(sourceRoot)) {
  const skillDirectory = join(sourceRoot, entry);
  if (!statSync(skillDirectory).isDirectory()) continue;
  skills[entry] = Object.fromEntries(
    filesBelow(skillDirectory).map((path) => [
      relative(skillDirectory, path).replaceAll("\\", "/"),
      readFileSync(path, "utf8"),
    ]),
  );
}

writeFileSync(
  output,
  `// Generated by scripts/embed-predefined-skills.mjs.\nexport const PREDEFINED_SKILLS: Readonly<Record<string, Readonly<Record<string, string>>>> = ${JSON.stringify(skills, null, 2)};\n`,
);
process.stdout.write(`embedded_predefined_skills count=${Object.keys(skills).length}\n`);
